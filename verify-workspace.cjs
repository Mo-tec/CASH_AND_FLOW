const fs=require('fs'),vm=require('vm'),assert=require('assert');
const code=fs.readFileSync('business.js','utf8');
const ctx={validRecord:r=>r&&['business','personal'].includes(r.account),validOrder:o=>o&&['business','personal'].includes(o.account),validStock:()=>true,isId:s=>typeof s==='string',cleanText:(s,n)=>typeof s==='string'&&s.length<=n};
vm.createContext(ctx);
vm.runInContext(code.slice(code.indexOf('function validateData'),code.indexOf('let notebook')),ctx);
const input={version:2,records:[{id:'a',account:'personal',type:'expense',amount:100},{id:'b',account:'business',type:'income',amount:250}],orders:[],inventory:[]};
const output=ctx.validateData(input);
assert.equal(output.records.length,2);
assert(output.records.every(r=>r.account==='business'));
assert.equal(input.records[0].account,'personal');
assert.equal(output.records.reduce((n,r)=>n+(r.type==='income'?r.amount:-r.amount),0),150);
assert.equal(ctx.validateData({...input,notebook:'Mipango yangu'}).notebook,'Mipango yangu');
assert.throws(()=>ctx.validateData({...input,notebook:123}));
const migrated=ctx.validateData({...input,notebook:'Maandishi ya zamani'});
assert.equal(migrated.notes[0].body,'Maandishi ya zamani');
assert.equal(ctx.validateData({...input,notes:[{id:'note1',title:'Kazi',body:'Mpango',updatedAt:'2026-10-20T10:00:00Z'}]}).notes.length,1);
assert.throws(()=>ctx.validateData({...input,notes:[{id:'note1',title:'',body:'Mpango',updatedAt:'bad'}]}));
for(const file of ['business.js','workspace.js','sw.js'])new vm.Script(fs.readFileSync(file,'utf8'));
const html=fs.readFileSync('index.html','utf8');
for(const match of html.matchAll(/<script(?:\s[^>]*)?>([\s\S]*?)<\/script>/g))new vm.Script(match[1]);
assert(!html.includes('data-account="personal"'));
assert(fs.readFileSync('sw.js','utf8').includes("'./workspace.js'"));
console.log('PASS: account migration, preserved totals, notebook validation, scripts and offline asset.');
