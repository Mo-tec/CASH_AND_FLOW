const assert=require('node:assert/strict');
const fs=require('node:fs');
const vm=require('node:vm');
const html=fs.readFileSync('index.html','utf8');
const store=new Map(),events=[];
const context={SETTINGS_KEY:'settings',localStorage:{getItem:key=>store.get(key)||null,setItem:(key,value)=>store.set(key,value)},window:{dispatchEvent:event=>events.push(event.type)},Event:class{constructor(type){this.type=type}},JSON};
vm.createContext(context);
vm.runInContext(html.slice(html.indexOf('function settings()'),html.indexOf('function t(')),context);
vm.runInContext('saveSettings({foldOpen_stockPanel:true})',context);
assert.equal(events.length,0);
vm.runInContext("saveSettings({lang:'en'})",context);
assert.deepEqual(events,['motec:settings-commit']);
vm.runInContext("saveSettings({lang:'en'})",context);
assert.equal(events.length,1);
vm.runInContext("saveSettings({categories:['Print']})",context);
assert.equal(events.length,2);
const cloud=fs.readFileSync('firebase-cloud.js','utf8');
const projection=cloud.slice(cloud.indexOf('const syncSettings ='),cloud.indexOf('async function fingerprint'));
vm.runInContext(projection+'\nthis.snapshotData=snapshotData',context);
const d={records:[],orders:[],inventory:[]};
const a=context.snapshotData({...d,settings:{lang:'sw',categories:['Print']}});
const b=context.snapshotData({...d,settings:{lang:'en',categories:['Print']}});
assert.notEqual(JSON.stringify(a),JSON.stringify(b));
assert.equal(a.settings.foldOpen_stockPanel,undefined);
assert(cloud.includes("window.addEventListener('motec:settings-commit'"));
assert(fs.readFileSync('business.js','utf8').includes('if(raw.settings)saveSettings(safeBackupSettings(raw.settings))'));
console.log('PASS: material settings trigger sync; view state does not; cloud snapshot includes settings.');
